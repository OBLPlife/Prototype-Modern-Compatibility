"""Compile generated peripheral artwork and original-frame light measurements.

FFmpeg prepares the generated artwork. Original videos supply only one RGB
average per frame; no original image/audio bytes are embedded or modified.
"""
import argparse,hashlib,json,struct,subprocess
from pathlib import Path
p=argparse.ArgumentParser()
p.add_argument('--work',type=Path,required=True)
p.add_argument('--ffmpeg',required=True)
a=p.parse_args()
root=Path(__file__).resolve().parents[1]
art=a.work/'title-outpaint-generated.png'
# Two independent outer strips. The generated central subject is discarded.
graph="[0:v]split[l][r];[l]crop=244:823:0:0,scale=128:512,format=gbrp,geq=r='r(X,Y)*min(1,(127-X)/40)':g='g(X,Y)*min(1,(127-X)/40)':b='b(X,Y)*min(1,(127-X)/40)'[a];[r]crop=244:823:1667:0,scale=128:512,format=gbrp,geq=r='r(X,Y)*min(1,X/40)':g='g(X,Y)*min(1,X/40)':b='b(X,Y)*min(1,X/40)'[b];[a][b]hstack,format=rgb565le[out]"
raw=subprocess.check_output([a.ffmpeg,'-v','error','-i',str(art),'-filter_complex_threads','1','-filter_complex',graph,'-map','[out]','-frames:v','1','-f','rawvideo','-'])
assert len(raw)==256*512*2
pixels=struct.unpack('<'+str(len(raw)//2)+'H',raw)
runs=[]
for pixel in pixels:
    if runs and runs[-1][1]==pixel and runs[-1][0]<65535:runs[-1][0]+=1
    else:runs.append([1,pixel])
header='// Generated by tools/build_movie_canvas.py. Peripheral generated art only.\n#pragma once\n'
header+='static const unsigned short movieCanvasRuns[][2]={\n'
header+='\n'.join('{'+str(n)+','+hex(c)+'},' for n,c in runs)+'\n};\n'
report={'generatedArtworkSha256':hashlib.sha256(art.read_bytes()).hexdigest(),'texture':[256,512],
        'runs':len(runs),'generatedCenterUsed':False,'originalVideosModified':False,'movies':[]}
for name,frames in [('logos',427),('title',612),('ambient',1808)]:
    video=a.work/f'{name}-candidate.bik'
    rgb=subprocess.check_output([a.ffmpeg,'-v','error','-i',str(video),'-an','-vf','crop=1280:220:0:0,scale=1:1:flags=area,format=rgb24','-f','rawvideo','-'])
    assert len(rgb)==3*frames
    values=[min(255,rgb[3*i]*30) for i in range(frames)]
    # Keep transitions tied to decoded frames, including skip/loop. A short
    # centered mean reduces quantization without a wall-clock animation drift.
    smooth=[round(sum(values[max(0,i-2):min(frames,i+3)])/len(values[max(0,i-2):min(frames,i+3)])) if values[i] else 0 for i in range(frames)]
    header+=f'static const unsigned char movieLight_{name}[]={{'+','.join(map(str,smooth))+'};\n'
    report['movies'].append({'name':name,'frames':frames,'sourceSha256':hashlib.sha256(video.read_bytes()).hexdigest(),'lightMinMax':[min(smooth),max(smooth)]})
(root/'src/movie_canvas_art.h').write_text(header,encoding='utf-8')
(root/'evidence/movie-canvas-art-0.2.10.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
print(json.dumps(report))
